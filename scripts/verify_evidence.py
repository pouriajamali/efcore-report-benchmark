"""Verify recorded local measurements. This does not run SQL or remeasure latency."""
from pathlib import Path
from collections import defaultdict
import csv,hashlib,json,math,re,statistics,xml.etree.ElementTree as ET

root=Path(__file__).resolve().parent.parent
result=root/'results'
for line in (root/'SHA256SUMS.txt').read_text().splitlines():
    expected,name=line.split('  ',1)
    assert hashlib.sha256((root/name).read_bytes()).hexdigest()==expected,name
build=json.loads((result/'build-metadata.json').read_text())
for name,expected in build['sources'].items():
    assert hashlib.sha256((root/name).read_bytes()).hexdigest()==expected,name
raw=list(csv.DictReader((result/'samples.csv').open(encoding='utf8')))
assert len(raw)==1350
assert sum(x['phase']=='steady' for x in raw)==1080
grouped=defaultdict(list);triplets=defaultdict(list)
for row in raw:
    assert float(row['client_ms'])>=0
    grouped[(row['phase'],row['band'],int(row['size']),row['mode'])].append(row)
    triplets[(row['phase'],row['round'],row['sample'],row['band'],row['size'])].append(row)
for rows in triplets.values():
    assert len(rows)==3
    for field in ('result_sha256','result_groups','matching_transactions','total_amount_minor'):
        assert len({x[field] for x in rows})==1,field
summary=json.loads((result/'summary.json').read_text())
assert len(grouped)==len(summary['summary'])==36
for s in summary['summary']:
    rows=grouped[(s['phase'],s['band'],s['size'],s['mode'])]
    times=sorted(float(x['client_ms']) for x in rows)
    assert len(times)==s['n']==(60 if s['phase']=='steady' else 15)
    assert math.isclose(statistics.median(times),s['median_ms'],abs_tol=1e-9)
    assert math.isclose(times[math.ceil(.95*len(times))-1],s['p95_ms'],abs_tol=1e-9)
    assert len({x['sql_shape_sha256'] for x in rows})==s['unique_sql_shapes']

def key(sql):
    m=re.search(r'_steady_(hot|cold)_(5|50|500)_(MultipleParameters|Parameter|Constant)\b',sql)
    assert m
    return m[1],int(m[2]),m[3]
counters=defaultdict(lambda:defaultdict(float))
for i in range(1,4):
    before={key(x['text']):x for x in json.loads((result/f'dmv-warmup-round-{i}.json').read_text())}
    after={key(x['text']):x for x in json.loads((result/f'dmv-steady-round-{i}.json').read_text())}
    assert len(before)==len(after)==18
    for k,a in after.items():
        b=before[k]
        assert a['plan_handle']==b['plan_handle'] and a['plan_generation_num']==b['plan_generation_num']
        assert a['execution_count']-b['execution_count']==20
        for field in ('total_worker_time','total_logical_reads','total_elapsed_time'):
            delta=a[field]-b[field];assert delta>=0;counters[k][field]+=delta
for s in summary['summary']:
    if s['phase']=='steady':
        c=counters[(s['band'],s['size'],s['mode'])]
        assert math.isclose(s['sql_cpu_mean_ms'],c['total_worker_time']/60000,abs_tol=1e-9)
        assert math.isclose(s['logical_reads_mean'],c['total_logical_reads']/60,abs_tol=1e-9)
fix=json.loads((result/'scoped-fix.json').read_text())
assert fix['AllResultsMatch'] and fix['ParameterCounts']==[500,1]
assert len(fix['Raw'])==60 and len({x['ResultSha256'] for x in fix['Raw']})==1
expected=grouped[('steady','cold',500,'Parameter')][0]['result_sha256']
assert all(x['ResultSha256']==expected for x in fix['Raw'])
for variant in ('default-scalar','scoped-EF.Parameter'):
    times=sorted(x['ClientMs'] for x in fix['Raw'] if x['Variant']==variant)
    assert len(times)==30
    assert math.isclose(statistics.median(times),summary['scoped_fix'][variant]['median_ms'],abs_tol=1e-9)
plans=list((result/'plans').glob('*.sqlplan'));assert len(plans)==18
ns={'s':'http://schemas.microsoft.com/sqlserver/2004/07/showplan'}
scalar=ET.parse(result/'plans/steady_cold_500_MultipleParameters.sqlplan')
assert sum(x.get('PhysicalOp')=='Constant Scan' for x in scalar.findall('.//s:RelOp',ns))==500
env=json.loads((result/'environment.json').read_text())
assert env['StoredDatasetSha256']==env['GeneratorDatasetSha256']=='8d98e4e43596fd0ab4fd2f2de5fa57b941bb72081ec53a96ebdd810ebbda2207'
assert len(triplets)==450
print('PASS: file/source hashes;36 summaries;450 matching result triplets;18 actual plans;60 scoped-fix observations.')
print('Recorded local evidence verified. No SQL timings were generated by this verifier.')
